-- 0422_section_ar: Arabic names of the register form sections (D36 follow-up: section_ar).
--
-- Additive and data-only. register_sections (0095) already carries name_ar and the sections admin already edits it;
-- the column was simply never filled. This migration
--   1. INSERTS the register_sections rows that fields reference but that were never created (15 section names on the
--      registers added after 0095), each with its Arabic name, and
--   2. backfills name_ar (clear MSA, consistent with the label_ar terms and the regSections web strings) for every
--      existing row that still has none. An Arabic name an admin already set is never overwritten.
-- The API then exposes it as the optional `section_ar` of a register field (contract 0.15.156); the web falls back to English.

-- 1. The referenced sections that have no register_sections row yet (registers seeded after 0095).
INSERT INTO register_sections (register_key, name_en, name_ar, sort_order)
SELECT v.register_key, v.name_en, v.name_ar,
       COALESCE((SELECT max(rs.sort_order) FROM register_sections rs WHERE rs.register_key = v.register_key), 0) + 10
  FROM (VALUES
  ('change_control', 'Affected', 'العناصر المتأثرة'),
  ('deliverables', 'Acceptance', 'القبول'),
  ('deliverables', 'Deliverable', 'المخرج'),
  ('deliverables', 'Links', 'الروابط'),
  ('deliverables', 'Remark', 'ملاحظة'),
  ('incidents', 'Incident', 'الحادث'),
  ('incidents', 'People and damage', 'الأشخاص والأضرار'),
  ('incidents', 'Remark', 'ملاحظة'),
  ('incidents', 'Resolution', 'المعالجة'),
  ('invoices', 'Amount', 'المبلغ'),
  ('invoices', 'Invoice', 'الفاتورة'),
  ('invoices', 'Payment', 'الدفع'),
  ('invoices', 'Remark', 'ملاحظة'),
  ('issues', 'Contractor', 'المقاول'),
  ('lessons_learned', 'Follow-up', 'المتابعة'),
  ('lessons_learned', 'Lesson', 'الدرس'),
  ('lessons_learned', 'Remark', 'ملاحظة'),
  ('quality', 'Contractor', 'المقاول'),
  ('warehouse', 'Procurement', 'المشتريات')
  ) AS v (register_key, name_en, name_ar)
WHERE NOT EXISTS (
  SELECT 1 FROM register_sections rs WHERE rs.register_key = v.register_key AND rs.name_en = v.name_en);

